"""Strict JSON Schema and Pydantic validation for Spark Reasoner verdicts.

All schemas sent to Meta Spark MUST comply with dev.meta.ai/docs/structured-output:
- additionalProperties: false on every object
- Every property listed in "required" (use nullable types for optional ones)
- No unsupported keywords ($schema, minimum, maximum, title, description on root)
- Nesting depth <= 3
- No recursive $ref references
"""

from __future__ import annotations

from enum import Enum
import json
import logging
from typing import Any

from pydantic import BaseModel, Field, field_validator, model_validator

logger = logging.getLogger("auditlens.providers.schemas")


class VerdictStatus(str, Enum):
    PASS = "pass"
    FAIL = "fail"
    UNSURE = "unsure"


