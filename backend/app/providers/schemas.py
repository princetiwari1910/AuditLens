# Keywords not supported by Meta strict structured-output
_UNSUPPORTED_KEYWORDS: set[str] = {
    "$schema", "title", "description", "default",
    "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum",
    "minLength", "maxLength", "pattern", "minItems", "maxItems",
    "uniqueItems", "$ref", "$defs", "definitions",
    "if", "then", "else", "allOf", "anyOf", "oneOf", "not",
}


def validate_meta_schema_compliance(schema: dict[str, Any], path: str = "root") -> list[str]:
    """Validate that a JSON schema dict complies with Meta structured-output rules.

    Returns a list of violation strings (empty = compliant).
    Rules enforced:
    - Every object must have additionalProperties: false
    - Every property defined in properties must appear in required
    - No unsupported keywords
    - Nesting depth <= 3
    """
    errors: list[str] = []
    try:
        depth = compute_schema_depth(schema)
        if depth > 3:
            errors.append(f"{path}: nesting depth {depth} exceeds maximum of 3")
    except ValueError as e:
        errors.append(f"{path}: {e}")

    _check_schema_node(schema, path, errors=errors)
    return errors


def _check_schema_node(node: Any, path: str, errors: list[str]) -> None:
    if not isinstance(node, dict):
        return

    # Check unsupported schema keywords (do not check property names inside 'properties' mapping)
    for key in node:
        if key in _UNSUPPORTED_KEYWORDS:
            errors.append(f"{path}: unsupported keyword '{key}'")

    # Check object rules
    if node.get("type") == "object":
        if node.get("additionalProperties") is not False:
            errors.append(f"{path}: object must have additionalProperties: false")

        props = node.get("properties", {})
        required = set(node.get("required", []))
        prop_names = set(props.keys())

        missing_from_required = prop_names - required
        if missing_from_required:
            errors.append(
                f"{path}: properties {sorted(missing_from_required)} not listed in required "
                "(use nullable types for optional fields)"
            )

        # Recurse into properties: pass prop_schema (the schema of the property), NOT the properties dict itself
        for prop_name, prop_schema in props.items():
            _check_schema_node(prop_schema, f"{path}.{prop_name}", errors)

    # Check array items
    if node.get("type") == "array":
        items = node.get("items")
        if isinstance(items, dict):
            _check_schema_node(items, f"{path}[items]", errors)


# ── Fix Action Planning Schema & Validation ───────────────────────────────────

class FixEffort(str, Enum):
    S = "S"
    M = "M"
    L = "L"


class FixAction(BaseModel):
    finding_id: str
    rule_id: str = ""
    severity: str = "medium"  # "high" | "medium" | "low"
    effort: FixEffort = FixEffort.M
    suggested_fix: str
    suggested_due_days: int = Field(ge=1, default=7)
    label: str = "AI-suggested (MOCK)"

    @field_validator("severity", mode="before")
    @classmethod
    def clean_severity(cls, v: Any) -> str:
        s = str(v).lower().strip() if v else "medium"
        return s if s in ("high", "medium", "low") else "medium"

    @field_validator("effort", mode="before")
    @classmethod
    def clean_effort(cls, v: Any) -> FixEffort:
        if isinstance(v, FixEffort):
            return v
        s = str(v).upper().strip() if v else "M"
        return FixEffort(s) if s in ("S", "M", "L") else FixEffort.M

    @field_validator("suggested_due_days", mode="before")
    @classmethod
    def clean_due_days(cls, v: Any) -> int:
        try:
            val = int(v)
            return max(1, val)
        except (ValueError, TypeError):
            return 7


def validate_fix_actions(
    raw_actions: Any,
    allowed_finding_ids: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Validate a list of fix actions against FixAction schema and known findings."""
    data = raw_actions
    if isinstance(raw_actions, str):
        try:
            data = json.loads(raw_actions)
        except Exception:
            return []

    if not isinstance(data, list):
        return []

    allowed_set = set(allowed_finding_ids) if allowed_finding_ids is not None else None
    results: list[dict[str, Any]] = []

    for item in data:
        if not isinstance(item, dict):
            continue
        try:
            action = FixAction.model_validate(item)
            if allowed_set is not None and action.finding_id not in allowed_set:
                continue
            results.append({
                "finding_id": action.finding_id,
                "rule_id": action.rule_id,
                "severity": action.severity,
                "effort": action.effort.value,
                "suggested_fix": action.suggested_fix,
                "suggested_due_days": action.suggested_due_days,
                "label": action.label,
            })
        except Exception as exc:
            logger.warning("FixAction validation error: %s", exc)
            continue

    return results


# ── Structured Voice Note Schema & Validation (WP13) ──────────────────────────

class StructuredVoiceNote(BaseModel):
    location: str = "general"
    issue: str = ""
    severity_hint: str = "medium"  # "high" | "medium" | "low"
    raw_transcript: str = ""

    @field_validator("severity_hint", mode="before")
    @classmethod
    def clean_severity_hint(cls, v: Any) -> str:
        s = str(v).lower().strip() if v else "medium"
        return s if s in ("high", "medium", "low") else "medium"


def validate_structured_voice_note(raw_data: Any) -> dict[str, Any]:
    """Validate structured voice note representation."""
    data = raw_data
    if isinstance(raw_data, str):
        try:
            data = json.loads(raw_data)
        except Exception:
            return {
                "location": "general",
                "issue": raw_data[:120],
                "severity_hint": "medium",
                "raw_transcript": raw_data,
            }

    if not isinstance(data, dict):
        return {
            "location": "general",
            "issue": str(data)[:120],
            "severity_hint": "medium",
            "raw_transcript": str(data),
        }

    try:
        vn = StructuredVoiceNote.model_validate(data)
        return {
            "location": vn.location,
            "issue": vn.issue,
            "severity_hint": vn.severity_hint,
            "raw_transcript": vn.raw_transcript,
        }
    except Exception as exc:
        logger.warning("StructuredVoiceNote validation error: %s", exc)
        return {
            "location": str(data.get("location", "general")),
            "issue": str(data.get("issue", "")),
            "severity_hint": "medium",
            "raw_transcript": str(data.get("raw_transcript", "")),
        }


